import { test, expect } from '@playwright/test';

test('planet streams triangular LOD and flight obeys gravity, hover, controls, and ground contact', async ({page})=>{
  test.setTimeout(120_000);
  await page.goto('/');
  const result=await page.evaluate(async()=>{
    const source=await(await fetch('/src/planet.ts')).text();
    const path=source.match(/from\s+["']([^"']+)["']/)![1];
    const THREE=await import(path);
    const {DesertSurface,DesertPlanet,PLANET_RADIUS,SURFACE_GRAVITY,faceDirection}=await import('/src/planet.ts');
    const {FlightPhysics,neutralInput}=await import('/src/flight-physics.ts');
    const surface=new DesertSurface(), same=new DesertSurface(), other=new DesertSurface('another-desert');
    const point=new THREE.Vector3(0,1,0);
    const height=surface.height(point), reproducible=same.height(point), different=other.height(point);
    const seam=faceDirection(0,1,0.3).distanceTo(faceDirection(5,-1,0.3));
    const flight=new FlightPhysics(surface,'poco'), input=neutralInput();
    const initial=flight.altitude;
    for(let i=0;i<1200;i++) flight.step(1/120,input);
    const hover={altitude:flight.altitude,speed:flight.speed};
    flight.ringEnabled=false;
    for(let i=0;i<240;i++) flight.step(1/120,input);
    const fall=hover.altitude-flight.altitude;
    flight.reset(); input.throttle=1;
    for(let i=0;i<720;i++) flight.step(1/120,input);
    const accelerated=flight.speed, before=flight.orientation.clone(); input.roll=1;
    for(let i=0;i<120;i++) flight.step(1/120,input);
    const turned=before.angleTo(flight.orientation);
    flight.reset(); flight.position.setLength(PLANET_RADIUS+surface.height(flight.position)+5);
    flight.velocity.set(0,-60,0); flight.ringEnabled=false;
    flight.step(1/30,neutralInput()); const contact={grounded:flight.grounded,altitude:flight.altitude};
    const planet=new DesertPlanet();
    const near=new THREE.Vector3(0,PLANET_RADIUS+height+180,0);
    for(let i=0;i<35;i++) planet.update(near,30);
    const nearStats={...planet.stats};
    let indicesValid=true, finite=true;
    planet.group.traverse((object:any)=>{if(object.isMesh){
      const positions=object.geometry.getAttribute('position');
      for(const index of object.geometry.index.array) if(index>=positions.count) indicesValid=false;
      for(const value of positions.array) if(!Number.isFinite(value)) finite=false;
    }});
    const far=new THREE.Vector3(0,PLANET_RADIUS+200000,0);
    for(let i=0;i<5;i++) planet.update(far,30);
    const farStats={...planet.stats}; planet.dispose();
    return {radius:PLANET_RADIUS,gravity:SURFACE_GRAVITY,halfGravity:surface.gravity(PLANET_RADIUS*2),height,reproducible,different,seam,initial,hover,fall,accelerated,turned,contact,nearStats,farStats,indicesValid,finite};
  });
  expect(result.radius).toBe(600000); expect(result.gravity).toBe(9.81);
  expect(result.halfGravity).toBeCloseTo(9.81/4,8);
  expect(result.height).toBe(result.reproducible); expect(result.height).not.toBe(result.different);
  expect(result.seam).toBeLessThan(1e-12);
  expect(result.hover.altitude).toBeCloseTo(result.initial,4); expect(result.hover.speed).toBeLessThan(0.01);
  expect(result.fall).toBeGreaterThan(15); expect(result.accelerated).toBeGreaterThan(80); expect(result.turned).toBeGreaterThan(0.5);
  expect(result.contact.grounded).toBe(true); expect(result.contact.altitude).toBeCloseTo(3.8,3);
  expect(result.nearStats.deepestLevel).toBeGreaterThan(10);
  expect(result.farStats.deepestLevel).toBeLessThan(result.nearStats.deepestLevel);
  expect(result.farStats.patches).toBeLessThan(result.nearStats.patches);
  expect(result.indicesValid).toBe(true); expect(result.finite).toBe(true);
});

test('select, launch, pilot, pause, and return to the hangar',async({page},testInfo)=>{
  test.setTimeout(120_000);
  const errors:string[]=[]; page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/'); await page.getByRole('button',{name:'Free flight'}).click();
  await page.screenshot({path:testInfo.outputPath('launch-selection.png')});
  await page.getByRole('button',{name:'Launch free flight'}).click({timeout:10000});
  const flight=page.getByRole('region',{name:'Free flight',exact:true});
  await expect(flight).toHaveAttribute('data-ready','true');
  await expect(flight).toHaveAttribute('data-radius','600000');
  await expect.poll(async()=>Number(await flight.getAttribute('data-lod')),{timeout:45000}).toBeGreaterThan(10);
  await expect(flight).toHaveAttribute('data-terrain-pending','0',{timeout:30000});
  await page.screenshot({path:testInfo.outputPath('desert-flight.png')});
  await expect.poll(async()=>Number(await flight.getAttribute('data-speed'))).toBeLessThan(0.1);
  await page.keyboard.down('w');
  await expect.poll(async()=>Number(await flight.getAttribute('data-speed')),{timeout:15000}).toBeGreaterThan(15);
  await page.keyboard.up('w');
  await page.keyboard.down('Shift');
  await expect.poll(async()=>Number(await flight.getAttribute('data-altitude')),{timeout:10000}).toBeGreaterThan(185);
  await page.keyboard.up('Shift');
  await page.keyboard.down('Control');
  await expect(flight).toHaveAttribute('data-input-vertical','-1');
  await page.keyboard.up('Control');
  await page.keyboard.down('a'); await expect(flight).toHaveAttribute('data-input-yaw','1'); await page.keyboard.up('a');
  await page.keyboard.down('d'); await expect(flight).toHaveAttribute('data-input-yaw','-1'); await page.keyboard.up('d');
  const mouseInput=async()=>page.evaluate(async()=>{
    const screen=document.querySelector<HTMLElement>('.flight-screen')!, canvas=screen.querySelector('canvas')!;
    const samples:{pitch:number;roll:number}[]=[];
    for(let i=0;i<8;i++) {
      canvas.dispatchEvent(new MouseEvent('mousemove',{bubbles:true,movementX:8,movementY:-8}));
      await new Promise<void>(resolve=>requestAnimationFrame(()=>resolve()));
      samples.push({pitch:Number(screen.dataset.inputPitch),roll:Number(screen.dataset.inputRoll)});
    }
    return samples;
  });
  const normalMouse=await mouseInput();
  expect(normalMouse.some(input=>input.pitch<0 && input.roll<0)).toBe(true);
  await page.getByRole('button',{name:'Controls',exact:true}).first().click();
  const settings=page.getByRole('region',{name:'Controls',exact:true});
  await expect(settings).toBeVisible();
  await settings.getByRole('checkbox',{name:'Invert mouse pitch'}).check();
  await expect(flight).toHaveAttribute('data-invert-pitch','true');
  await page.screenshot({path:testInfo.outputPath('controls-menu.png')});
  await settings.getByRole('button',{name:'Back',exact:true}).click();
  await page.getByRole('button',{name:'Resume flight',exact:true}).click();
  const invertedMouse=await mouseInput();
  expect(invertedMouse.some(input=>input.pitch>0 && input.roll<0)).toBe(true);
  await page.keyboard.press('h'); await expect(flight).toHaveAttribute('data-ring','false');
  await page.keyboard.press('Escape'); await expect(flight).toHaveAttribute('data-paused','true');
  await page.getByRole('button',{name:'Reset position'}).click();
  await expect(flight).toHaveAttribute('data-ring','true');
  await page.keyboard.press('v');
  await page.screenshot({path:testInfo.outputPath('terrain-triangles.png')});
  await page.keyboard.press('Escape'); await page.getByRole('button',{name:'Return to hangar'}).click();
  await expect(page.getByRole('heading',{name:'Select your ship'})).toBeVisible();
  await expect(flight).toHaveCount(0); expect(errors).toEqual([]);
  expect(await page.evaluate(()=>localStorage.getItem('skyward.invertMousePitch'))).toBe('true');
  await page.getByRole('button',{name:'Launch free flight'}).click();
  await expect(flight).toHaveAttribute('data-invert-pitch','true');
  await page.getByRole('button',{name:'Controls',exact:true}).first().click();
  await expect(page.getByRole('checkbox',{name:'Invert mouse pitch'})).toBeChecked();
});
